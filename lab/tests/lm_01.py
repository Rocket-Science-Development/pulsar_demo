"""LM-01 - Model equality power by canary size (CanaryProbe + model_equality_test).

Answers are generated by the local Ollama of the host (127.0.0.1:11434) through the product `CanaryProbe` (with
`timed` retries), then compared with `pulsar_metrics.genai.model_equality.model_equality_test` (Hamming-kernel MMD
within prompts, permutation p-value, product defaults: 30 leading words, 1,000 permutations).

Canary sets: the 12 default prompts of `CanaryProbe` + 36 more of the same kind (public services, FR/EN), nested
(12 = defaults, 24, 48), answered 5, 10 or 20 times each. The prompts are synthetic, so their answers are kept
(lab/results/LM-01/answers/*.json, and the cache in /data/lab/cache/lm01).

Pairs (reference vs current):
  A/A            - same configuration, disjoint answers (level of the test, many random splits)
  quantisation   - llama3.2 3B q4_K_M / q8_0 / fp16; llama3.1 8B q4_K_M / q8_0
  size           - ministral-3 3b vs 8b
  family         - llama3.1 8B vs granite3.3 8B vs gemma3 4B vs ministral-3 8B
  system prompt  - llama3.2 3B q4 with another system prompt
  temperature    - llama3.2 3B q4 at 0.7 vs 0.3
Each pair x canary size is repeated 5 times (answers re-drawn from the generated pools); A/A is repeated more to
estimate the level.

    LAB_DRY=1 python -m lab.harness LM-01
    python -m lab.harness LM-01
"""

