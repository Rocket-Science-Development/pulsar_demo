def _pool(name, prompt):
    n_prompts, answers = CONFIGS[name][3]
    return answers if PROMPTS.index(prompt) < n_prompts else 0


def _ask_factory(model, temperature, system, stats, timeout=180):
    def ask(prompt):
        body = json.dumps({"model": model, "stream": False, "keep_alive": "10m",
                           "messages": [{"role": "system", "content": system}, {"role": "user", "content": prompt}],
                           "options": {"temperature": temperature, "num_predict": NUM_PREDICT}}).encode()
        req = urllib.request.Request(f"{OLLAMA}/api/chat", data=body, headers={"Content-Type": "application/json"})
        t0 = time.perf_counter()
        with urllib.request.urlopen(req, timeout=timeout) as r:
            out = json.loads(r.read())
        with stats["lock"]:
            stats["calls"] += 1
            stats["seconds"] += time.perf_counter() - t0
            stats["tokens"] += out.get("eval_count", 0)
        return out["message"]["content"]

    return ask


def _generate(name, ctx):
    """Pool of answers per prompt for one configuration, through CanaryProbe (cached, resumable by prompt)"""
    from pulsar_data_collection.genai.canary import CanaryProbe, timed

    model, temperature, system, _ = CONFIGS[name]
    path = CACHE / f"{name}.json"
    have = CanaryProbe.load(path) if path.exists() else {}
    todo = [p for p in PROMPTS if len(have.get(p, [])) < _pool(name, p)]
    from datetime import datetime, timezone

    if todo and datetime.now(timezone.utc) > datetime.fromisoformat(DEADLINE):
        ctx.note(f"{name}: generation skipped (deadline {DEADLINE}); {len(todo)} prompts incomplete")
        todo = []
    stats = {"lock": threading.Lock(), "calls": 0, "seconds": 0.0, "tokens": 0, "failures": 0}
    t0 = time.perf_counter()
    if todo:
        _ask_factory(model, temperature, system, stats, timeout=LOAD_TIMEOUT)("Hello")  # load once, no retry
        ask = timed(_ask_factory(model, temperature, system, stats))
        chunks = [todo[i::CONCURRENCY] for i in range(CONCURRENCY) if todo[i::CONCURRENCY]]

        def work(chunk):
            need = {p: _pool(name, p) - len(have.get(p, [])) for p in chunk}
            # each prompt is asked as many times as it still needs (CanaryProbe asks every prompt `samples` times)
            res = {p: [] for p in chunk}
            for n in sorted(set(need.values())):
                group = [p for p in chunk if need[p] == n]
                probe = CanaryProbe(prompts=group, samples=n)
                res.update(probe.run(ask))
                stats["failures"] += probe.failures
            return {p: res[p][:need[p]] for p in chunk}

        with ThreadPoolExecutor(len(chunks)) as ex:
            for part in ex.map(work, chunks):
                for p, a in part.items():
                    have.setdefault(p, []).extend(a)
        CanaryProbe.save(have, path, model=model, temperature=temperature, system=system, num_predict=NUM_PREDICT)
    wall = time.perf_counter() - t0
    out_dir = ctx.workdir / "answers"
    out_dir.mkdir(exist_ok=True)
    if path.exists():
        (out_dir / f"{name}.json").write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
    return have, {"wall_s": round(wall, 1), "calls": stats["calls"], "failures": stats["failures"],
                  "tokens_per_s": round(stats["tokens"] / wall, 1) if wall and stats["tokens"] else None}


def _test(args):
    """One equality test (run in a worker process)"""
    ref, cur, n_perm, seed = args
    from pulsar_metrics.genai.model_equality import model_equality_test

    r = model_equality_test(ref, cur, n_permutations=n_perm, seed=seed)
    return r.p_value, r.statistic


def _key(ref, cur):
    """Identity of a draw as sets of answers (the statistic does not depend on the order within a prompt)"""
    return hash(json.dumps([{p: sorted(v) for p, v in ref.items()}, {p: sorted(v) for p, v in cur.items()}], sort_keys=True))


def _draw(pool_ans, prompts, k, rng, exclude=None):
    out, used = {}, {}
    for p in prompts:
        idx = list(range(len(pool_ans[p])))
        if exclude is not None:
            idx = [i for i in idx if i not in exclude[p]]
        pick = rng.sample(idx, min(k, len(idx)))
        out[p], used[p] = [pool_ans[p][i] for i in pick], set(pick)
    return out, used


def run(ctx):
    rng = random.Random(SEED)
    CACHE.mkdir(parents=True, exist_ok=True)
    pools, gen = {}, {}
    skip = set(filter(None, os.environ.get("LM01_SKIP", "").split(",")))
    for name in CONFIGS:
        if name in skip:
            ctx.note(f"{name}: skipped (LM01_SKIP); cached answers used if any")
            path = CACHE / f"{name}.json"
            if path.exists():
                from pulsar_data_collection.genai.canary import CanaryProbe

                pools[name] = CanaryProbe.load(path)
            continue
        try:
            pools[name], gen[name] = _generate(name, ctx)
        except Exception as exc:  # noqa: BLE001 - one model failing must not stop the test
            ctx.note(f"generation failed for {name}: {type(exc).__name__}: {exc}")
    # identical answers across samples (temperature too low / deterministic decoding) make the test degenerate
    diversity = {n: round(float(np.mean([len(set(a)) / len(a) for a in p.values() if a])), 3) for n, p in pools.items()}

    jobs, meta = [], []
    for name, (kind, a, b) in PAIRS.items():
        if a not in pools or b not in pools:
            continue
        for npr in PROMPT_SIZES:
            for k in ANSWER_SIZES:
                if k > min(len(pools[x].get(p, [])) for x in (a, b) for p in PROMPTS[:npr]):
                    continue
                for rep in range(REPS):
                    ref, _ = _draw(pools[a], PROMPTS[:npr], k, rng)
                    cur, _ = _draw(pools[b], PROMPTS[:npr], k, rng)
                    jobs.append((ref, cur, 1000, rep))
                    meta.append((name, kind, npr, k, rep, _key(ref, cur)))
    for name in AA:
        if name not in pools:
            continue
        for npr in PROMPT_SIZES:
            for k in ANSWER_SIZES:
                if 2 * k > min(len(pools[name].get(p, [])) for p in PROMPTS[:npr]):
                    continue
                for rep in range(AA_REPS):
                    ref, used = _draw(pools[name], PROMPTS[:npr], k, rng)
                    cur, _ = _draw(pools[name], PROMPTS[:npr], k, rng, exclude=used)
                    jobs.append((ref, cur, 1000 if rep < REPS else 200, rep))
                    meta.append((f"aa_{name}", "aa", npr, k, rep, _key(ref, cur)))
    t0 = time.perf_counter()
    with ProcessPoolExecutor(WORKERS) as ex:
        results = list(ex.map(_test, jobs, chunksize=4))
    test_s = time.perf_counter() - t0

    cells = {}
    for (name, kind, npr, k, rep, key), (p, stat) in zip(meta, results):
        c = cells.setdefault((name, npr, k), {"pair": name, "kind": kind, "prompts": npr, "answers": k,
                                              "answers_total": npr * k, "p": [], "stat": []})
        c["p"].append(p)
        c.setdefault("keys", set()).add(key)
        c["stat"].append(stat)
    table = []
    for c in cells.values():
        p = np.array(c["p"])
        table.append({k: v for k, v in c.items() if k not in ("p", "stat", "keys")} | {
            "reps": len(p), "distinct_draws": len(c["keys"]), "detection_rate": round(float((p < 0.05).mean()), 3),
            "p_median": round(float(np.median(p)), 4), "stat_median": round(float(np.median(c["stat"])), 5)})
    table.sort(key=lambda r: (r["kind"], r["pair"], r["prompts"], r["answers"]))
    (ctx.workdir / "power_table.json").write_text(json.dumps(table, indent=1), encoding="utf-8")

    def rate(pair, npr, k):
        return next((r["detection_rate"] for r in table if r["pair"] == pair and r["prompts"] == npr and r["answers"] == k), None)

    smallest = (PROMPT_SIZES[0], ANSWER_SIZES[0])
    aa_rows = [r for r in table if r["kind"] == "aa"]
    aa_level_max = max((r["detection_rate"] for r in aa_rows), default=None)
    aa_rej = sum(round(r["detection_rate"] * r["reps"]) for r in aa_rows)
    aa_n = sum(r["reps"] for r in aa_rows)
    aa_pooled = aa_rej / aa_n if aa_n else None
    if aa_rows:
        from scipy.stats import binomtest

        ctx.note(f"A/A pooled over {len(aa_rows)} cells: {aa_rej}/{aa_n} = {aa_pooled:.3f} rejections at 5 % "
                 f"(binomial p vs 0.05: {binomtest(aa_rej, aa_n, 0.05, alternative='greater').pvalue:.3f}); splits "
                 "drawn from one pool are not independent across cells")
    family_rows = [r for r in table if r["kind"] == "family" and (r["prompts"], r["answers"]) == smallest]
    family_power_smallest = min((r["detection_rate"] for r in family_rows), default=None)

    def minimal(pair, target=0.8):
        # a cell counts only with >= 3 distinct draws (when a pool holds exactly k answers, every rep is the same test)
        ok = [r for r in table if r["pair"] == pair and r["detection_rate"] >= target and r["distinct_draws"] >= 3]
        return min(ok, key=lambda r: (r["answers_total"], r["prompts"]))["answers_total"] if ok else None

    minimal_sizes = {name: minimal(name) for name in PAIRS if any(r["pair"] == name for r in table)}
    metrics = {
        "aa_level_max": aa_level_max, "aa_level_pooled": round(aa_pooled, 4) if aa_pooled is not None else None,
        "aa_levels": {f"{r['pair']} {r['prompts']}x{r['answers']}": r["detection_rate"] for r in aa_rows},
        "family_power_smallest": family_power_smallest,
        "power_at_smallest": {r["pair"]: r["detection_rate"] for r in table
                              if (r["prompts"], r["answers"]) == smallest and r["kind"] != "aa"},
        "power_at_largest": {name: max((r for r in table if r["pair"] == name), key=lambda r: r["answers_total"])
                             ["detection_rate"] for name in PAIRS if any(r["pair"] == name for r in table)},
        "largest_size_by_pair": {name: max(r["answers_total"] for r in table if r["pair"] == name)
                                 for name in PAIRS if any(r["pair"] == name for r in table)},
        "minimal_answers_for_80pct": minimal_sizes,
        "q4_q8_3b_at_12x5": rate("quant_3b_q4_q8", 12, 5), "q4_q8_8b_at_12x5": rate("quant_8b_q4_q8", 12, 5),
        "answer_diversity": diversity, "generation": gen, "tests": len(jobs), "test_seconds": round(test_s, 1),
        "test_seconds_per_test": round(test_s * WORKERS / max(len(jobs), 1), 3),
    }

    # ---------------------------------------------------------------- limits
    if aa_level_max is not None and aa_level_max > 0.05:
        worst = max(aa_rows, key=lambda r: r["detection_rate"])
        reps = worst["reps"]
        # binomial 95 % upper noise for the observed number of reps
        se = (0.05 * 0.95 / reps) ** 0.5
        if worst["detection_rate"] > 0.05 + 2 * se:
            ctx.limit(
                f"Model equality test rejects too often under A/A: {worst['detection_rate']:.0%} at "
                f"{worst['prompts']}x{worst['answers']} (target <= 5 %)",
                f"{reps} disjoint A/A splits of the {worst['pair'][3:]} pool; all A/A cells: {metrics['aa_levels']}",
                "Check exchangeability of the answers (Ollama caching or batching can correlate answers generated "
                "together); generate reference and current at different times in the canary schedule.",
                "major")
    for name in [n for n, (kind, _, _) in PAIRS.items() if kind == "quantisation"]:
        r12 = rate(name, PROMPT_SIZES[0], ANSWER_SIZES[0])
        if name == "quant_3b_q8_fp16":
            # Not a limit (refuted by the night's verifier): q8_0 vs fp16 is a near-zero change, so staying silent is
            # the right behaviour. Documented only, with the largest size actually tested.
            if r12 is not None:
                ctx.note(f"q8_0 vs fp16 (llama3.2 3B): detection {r12:.0%} at {PROMPT_SIZES[0]}x{ANSWER_SIZES[0]}; "
                         f"near-zero change, silence expected; not tested beyond "
                         f"{metrics['largest_size_by_pair'].get(name)} answers")
            continue
        if r12 is not None and r12 < 0.8:
            ctx.limit(
                f"Quantisation change {name.replace('quant_', '')} is not reliably detected by the default canary "
                f"({PROMPT_SIZES[0]} prompts x {ANSWER_SIZES[0]} answers = {PROMPT_SIZES[0] * ANSWER_SIZES[0]})",
                f"detection rate {r12:.0%} over {REPS} reps at {PROMPT_SIZES[0]}x{ANSWER_SIZES[0]}; by size: "
                + ", ".join(f"{r['prompts']}x{r['answers']} {r['detection_rate']:.0%}" + (f" ({r['distinct_draws']} distinct draw)" if r['distinct_draws'] < 3 else "") for r in table if r["pair"] == name)
                + f"; minimal size for 80 %: {minimal_sizes.get(name) or 'not reached up to ' + str(metrics['largest_size_by_pair'].get(name)) + ' answers'}",
                "Document the canary size needed for quantisation (see the power table); default CanaryProbe to the "
                "size that reaches 80 % here, or compare with the model's own tokenizer and a longer prefix "
                "(length 30 -> 60), which keeps more of the subtle token differences.",
                "major")
    for name, (kind, _, _) in PAIRS.items():
        if kind in ("family", "size") and rate(name, *smallest) is not None and rate(name, *smallest) < 0.8:
            ctx.limit(
                f"{kind.title()} change {name} missed at the smallest canary ({smallest[0]}x{smallest[1]})",
                f"detection rate {rate(name, *smallest):.0%}; minimal size for 80 %: {minimal_sizes.get(name)}",
                "Raise the default canary size or the compared prefix length.", "major")
    for name in ("system_prompt", "temperature_07_03"):
        if name in PAIRS and rate(name, *smallest) is not None and rate(name, *smallest) < 0.8:
            ctx.limit(
                f"{name.replace('_', ' ')} change missed at the default canary size ({smallest[0]}x{smallest[1]})",
                "detection by size: " + ", ".join(f"{r['prompts']}x{r['answers']} {r['detection_rate']:.0%}" + (f" ({r['distinct_draws']} distinct draw)" if r['distinct_draws'] < 3 else "")
                                                  for r in table if r["pair"] == name)
                + f"; minimal size for 80 %: {minimal_sizes.get(name) or 'not reached'}",
                "Document that the canary watches the served model, and that configuration changes (system prompt, "
                "temperature) need a larger canary or a dedicated check (log the configuration hash).",
                "minor")
    return metrics
